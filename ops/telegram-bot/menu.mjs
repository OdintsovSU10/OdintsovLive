// Строка для системного промпта: что пользователь выбрал в меню
export const modeHint = tool => {
  const button = Object.values(MENU_BUTTONS).find(b => b.mode === tool)
  if (!button) return ''
  const tools = [button.mode, ...(button.also || [])].join(' или ')
  return `Пользователь выбрал в меню «${button.label}»: запиши это сообщение инструментом ${tools} (если подходит по смыслу).`
}
